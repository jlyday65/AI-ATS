#!/usr/bin/env node
/**
 * Fix Railway ERR_MODULE_NOT_FOUND for ATS routes imported by server.js
 * but missing from the Gina deploy (common after partial patches / rollbacks).
 *
 * Copies every gina-express route/lib file that server.js imports, if missing
 * or always refresh from AI-ATS kit.
 *
 * ONE LINE:
 *   node gina-express/frontend/fix-missing-ats-routes.mjs ~/lyday-gina-backend/gina-backend
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.join(__dirname, "..");
const rootArg = String(process.argv[2] || "")
  .trim()
  .replace(/^~/, process.env.HOME || "");
const root = path.resolve(rootArg);
const ginaDir = fs.existsSync(path.join(root, "server.js"))
  ? root
  : fs.existsSync(path.join(root, "gina-backend", "server.js"))
    ? path.join(root, "gina-backend")
    : root;

const serverPath = path.join(ginaDir, "server.js");
if (!fs.existsSync(serverPath)) {
  console.error(
    "Usage (one line): node fix-missing-ats-routes.mjs ~/lyday-gina-backend/gina-backend",
  );
  process.exit(1);
}

const server = fs.readFileSync(serverPath, "utf8");

/** Known kit files keyed by import path used in server.js */
const KIT = [
  {
    importRe: /routes\/pipeline-briefing\.js/,
    files: [
      "routes/pipeline-briefing.js",
      "briefing/format-pipeline-stage-counts.js",
      "lib/kimberley-notes.js",
    ],
  },
  {
    importRe: /routes\/kimberley-notes\.js/,
    files: ["routes/kimberley-notes.js", "lib/kimberley-notes.js"],
  },
  {
    importRe: /routes\/candidate-files\.js/,
    files: ["routes/candidate-files.js", "lib/candidate-files.js"],
  },
  {
    importRe: /candidate-file-page\.route\.js/,
    files: [], // generated by patch-candidate-files; ensure HTML exists
    ensurePage: true,
  },
];

function copyKitFile(rel) {
  const src = path.join(pkg, rel);
  const dest = path.join(ginaDir, rel);
  if (!fs.existsSync(src)) {
    console.warn("Kit missing (skip):", rel);
    return false;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
  console.log("Copied", rel);
  return true;
}

let copied = 0;
for (const item of KIT) {
  if (!item.importRe.test(server)) continue;
  console.log("server.js imports match:", item.importRe);
  for (const rel of item.files) {
    if (copyKitFile(rel)) copied++;
  }
  if (item.ensurePage) {
    const htmlSrc = path.join(pkg, "frontend/candidate-file.html");
    if (fs.existsSync(htmlSrc)) {
      const publicHtml = path.join(
        ginaDir,
        "frontend/public/candidate-file.html",
      );
      fs.mkdirSync(path.dirname(publicHtml), { recursive: true });
      fs.copyFileSync(htmlSrc, publicHtml);
      // Rebuild embedded page route if missing
      const pageRoute = path.join(ginaDir, "candidate-file-page.route.js");
      if (!fs.existsSync(pageRoute)) {
        const html = fs.readFileSync(publicHtml, "utf8");
        fs.writeFileSync(
          pageRoute,
          `const HTML = ${JSON.stringify(html)};
export function mountCandidateFilePage(app) {
  const send = (_req, res) => res.status(200).type("html").send(HTML);
  app.get("/candidate-file", send);
  app.get("/candidate-file.html", send);
  console.log("[candidate-file] page route: /candidate-file");
}
export default mountCandidateFilePage;
`,
          "utf8",
        );
        console.log("Wrote candidate-file-page.route.js");
        copied++;
      }
    }
  }
}

// Also scan server.js for any ./routes/*.js import and warn if file missing
const re = /from\s*["'](\.\/routes\/[^"']+)["']/g;
let m;
const missing = [];
while ((m = re.exec(server))) {
  const rel = m[1].replace(/^\.\//, "");
  const abs = path.join(ginaDir, rel);
  if (!fs.existsSync(abs)) missing.push(rel);
}

if (missing.length) {
  console.log("\nStill missing after copy:");
  for (const rel of missing) console.log(" -", rel);
}

// Verify pipeline-briefing specifically
const pipe = path.join(ginaDir, "routes/pipeline-briefing.js");
const fmt = path.join(ginaDir, "briefing/format-pipeline-stage-counts.js");
if (/pipeline-briefing/.test(server)) {
  if (!fs.existsSync(pipe) || !fs.existsSync(fmt)) {
    console.error("FAILED: pipeline-briefing still incomplete");
    process.exit(2);
  }
  console.log("OK: routes/pipeline-briefing.js + briefing formatter present");
}

console.log(`
Next (commit the route files Railway is missing):
  cd ~/lyday-gina-backend
  git add gina-backend/routes gina-backend/briefing gina-backend/lib gina-backend/candidate-file-page.route.js gina-backend/frontend/public/candidate-file.html gina-backend/server.js gina-backend/gina.js
  git status
  git commit -m "Add missing ATS route modules for Railway boot"
  git push origin main

Railway Redeploy — confirm logs show server listening (no ERR_MODULE_NOT_FOUND).
`);
